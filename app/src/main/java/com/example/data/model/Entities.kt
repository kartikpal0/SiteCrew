package com.example.data.model

import androidx.room.Entity
import androidx.room.PrimaryKey

enum class AttendanceStatus(val label: String, val multiplier: Double) {
    PRESENT("Full Day", 1.0),
    HALF_DAY("Half Day", 0.5),
    OVERTIME("Overtime", 1.0), // Base day + extra OT hours
    ABSENT("Absent", 0.0),
    LEAVE("On Leave", 0.0)
}

enum class SyncStatus {
    PENDING,
    SYNCED,
    FAILED
}

enum class WorkerTrade(val title: String) {
    MASON("Mason / Bricklayer"),
    CARPENTER("Carpenter"),
    ELECTRICIAN("Electrician"),
    PLUMBER("Plumber"),
    WELDER("Welder / Fabricator"),
    PAINTER("Painter"),
    SITE_SUPERVISOR("Site Supervisor"),
    GENERAL_LABORER("General Laborer")
}

@Entity(tableName = "admin_profiles")
data class AdminProfile(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val name: String,
    val phone: String,
    val pin: String = "1234",
    val companyName: String = "",
    val isLoggedIn: Boolean = true,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "construction_sites")
data class ConstructionSite(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val name: String, // Party / Project Name
    val clientName: String = "",
    val address: String,
    val latitude: Double,
    val longitude: Double,
    val geofenceRadiusMeters: Double = 200.0,
    val defaultDailyWage: Double = 140.0,
    val adminId: Long = 0,
    val isActive: Boolean = true,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "party_worker_invites")
data class PartyWorkerInvite(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val siteId: Long, // Associated Party ID
    val workerJoinCode: String, // Unique code generated by admin for each worker entry
    val trade: String = WorkerTrade.GENERAL_LABORER.title,
    val dailyWage: Double = 140.0,
    val isRedeemed: Boolean = false,
    val redeemedByWorkerId: Long? = null,
    val workerName: String = "",
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "workers")
data class Worker(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val name: String,
    val phone: String,
    val trade: String,
    val dailyWage: Double,
    val hourlyRate: Double = dailyWage / 8.0,
    val assignedSiteId: Long, // Party ID
    val joinCodeUsed: String = "", // The unique code used to join
    val upiId: String = "",
    val bankAccount: String = "",
    val bankIfsc: String = "",
    val emergencyContact: String = "",
    val isActive: Boolean = true,
    val syncStatus: SyncStatus = SyncStatus.SYNCED,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "attendance_records")
data class AttendanceRecord(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val workerId: Long,
    val siteId: Long,
    val date: String, // YYYY-MM-DD
    val status: AttendanceStatus,
    val checkInTimestamp: Long? = null,
    val checkOutTimestamp: Long? = null,
    val latitude: Double? = null,
    val longitude: Double? = null,
    val locationAccuracy: Float? = null,
    val distanceFromSiteMeters: Float? = null,
    val isWithinGeofence: Boolean = true,
    val overtimeHours: Double = 0.0,
    val notes: String = "",
    val syncStatus: SyncStatus = SyncStatus.PENDING,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "payment_records")
data class PaymentRecord(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val workerId: Long,
    val amount: Double,
    val paymentDate: Long = System.currentTimeMillis(),
    val paymentMethod: String, // UPI, Direct Bank Transfer, Card, Cash
    val transactionReference: String,
    val notes: String = "",
    val status: String = "SUCCESS",
    val syncStatus: SyncStatus = SyncStatus.PENDING
)

@Entity(tableName = "sync_logs")
data class SyncLog(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val action: String,
    val description: String,
    val status: SyncStatus,
    val timestamp: Long = System.currentTimeMillis(),
    val recordsCount: Int = 1
)
